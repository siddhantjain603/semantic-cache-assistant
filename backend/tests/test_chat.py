def test_chat_cache_miss(monkeypatch):
    mock_result = {
        "answer": "This answer was generated by the LLM.",
        "cache_hit": False,
        "matched_question": None,
        "distance": None,
    }

    mock_ask = MagicMock(return_value=mock_result)

    monkeypatch.setattr(
        chat_service,
        "ask",
        mock_ask,
    )

    monkeypatch.setattr(
        "backend.app.main.resources.initialize",
        lambda: None,
    )

    monkeypatch.setattr(
        "backend.app.main.resources.close",
        lambda: None,
    )

    monkeypatch.setattr(
        chat_service,
        "initialize",
        lambda: None,
    )

    with TestClient(app) as client:
        response = client.post(
            "/chat",
            json={"question": "Explain vector databases."},
        )

    assert response.status_code == 200
    assert response.json()["cache_hit"] is False
    assert response.json()["answer"] == "This answer was generated by the LLM."
    assert response.json()["matched_question"] is None
    assert response.json()["distance"] is None

    mock_ask.assert_called_once_with("Explain vector databases.")

