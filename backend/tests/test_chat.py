from unittest.mock import MagicMock

from fastapi.testclient import TestClient
from redis.exceptions import RedisError

from backend.app.api.routes.chat import chat_service
from backend.app.main import app


def test_chat_endpoint(monkeypatch):
    mock_result = {
        "answer": "Semantic caching reduces repeated LLM calls.",
        "cache_hit": False,
        "matched_question": None,
        "distance": None,
    }

    monkeypatch.setattr(
        chat_service,
        "ask",
        MagicMock(return_value=mock_result),
    )

    monkeypatch.setattr(
        "backend.app.main.resources.initialize",
        lambda: None,
    )

    monkeypatch.setattr(
        "backend.app.main.resources.close",
        lambda: None,
    )

    monkeypatch.setattr(
        chat_service,
        "initialize",
        lambda: None,
    )

    with TestClient(app) as client:
        response = client.post(
            "/chat",
            json={"question": "What is semantic caching?"},
        )

    assert response.status_code == 200
    assert response.json() == mock_result

